import turtle as t
wn = t.Screen()
wn.tracer(False)
t.shape("turtle")
LENGHT = 50
t.write("Click the turtle to make it draw a zeub!", align="center", font=("Arial", 16, "normal"))
def zeub(x, y):
    t.up()
    t.goto(x, y)
    t.setheading(0)
    t.down()
    t.fillcolor("black")
    t.begin_fill()
    t.circle(10)
    t.end_fill()
    t.up()
    t.forward(20)
    t.down()
    t.begin_fill()
    t.circle(10)
    t.end_fill()
    t.right(180)
    t.up()
    t.forward(20)
    t.down()
    t.left(90)
    t.begin_fill()
    t.forward(LENGHT)
    t.circle(10, 180)
    t.forward(LENGHT)
    t.end_fill()
    t.right(180)
    t.up()
    t.forward(LENGHT + 10)
    t.right(90)
    t.forward(10)
    t.down()
    t.right(90)
    t.color("white")
    t.forward(15)
    t.up()
    t.home()
    wn.update()
# The turtle itself is the clickable button; clicking elsewhere does nothing.
wn.onclick(zeub)
wn.mainloop()